"""A trivial, deterministic submission whose only job is to prove the pipe (OQ-6).

Design: agent_docs/q5_plan.md

## What this is for, and what it is not

This ranks candidates by `article_id`. It is not a recommender and it is not
expected to score well -- alphabetical order carries no information about what a
user will click, so it should land near random.

Its purpose is to answer one question before we spend 90 minutes encoding
246,502 test articles: **does the competition accept our file at all?** OQ-10
took the EB-NeRD format from the organisers' tooling rather than their scorer,
and OQ-1's MIND format, though scorer-confirmed, leaves one assumption open --
that the truth file covers `behaviors.tsv` in `behaviors.tsv` order. A rejection
here is cheap. A rejection after the full pipeline is a day.

## Deterministic, not random

`article_id` ascending, and no seed anywhere. A random baseline would need its
seed recorded to be reproducible (Q1.13), and the moment the file cannot be
regenerated byte for byte, the committed checksum stops meaning anything. Sorted
order costs nothing and removes the question.

The ranking is a strict total order because `article_id` values within one
impression are distinct, so no tie can reach `ranks_from_scores` -- which is
what `1/rank` requires.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import numpy as np
import polars as pl

from newsrec.submit import ebnerd_format, ebnerd_test, mind_format, mind_test
from newsrec.submit import format as fmt


def baseline_order(candidates: list[str]) -> np.ndarray:
    """Candidate indices, best-first, by `article_id` ascending.

    Returns positions, not ids: `ranks_from_scores` needs the permutation of
    candidate *positions* so it can invert it back onto the original order.
    """
    return np.argsort(np.asarray(candidates, dtype=object), kind="stable")


def mind_lines(path: Path | None = None) -> Iterator[tuple[str, str, int]]:
    """Yield `(line, impression_id, n_candidates)` for every test row, in order.

    The id and count come back alongside the line so the caller can validate
    against them without a second 1.4 GB pass over the source file.
    """
    for impression_id, candidates in mind_test.read_rows(path):
        ranks = fmt.ranks_from_scores(baseline_order(candidates), len(candidates))
        yield fmt.format_line(impression_id, ranks), impression_id, len(candidates)


def write_mind_baseline(
    out_dir: Path,
    source: Path | None = None,
) -> dict:
    """Write, archive and validate a MIND baseline submission. Returns a summary.

    Both artefacts are validated by reading them back, not by trusting what was
    just written: the text for its line format and coverage (Q5.3), and the zip
    for its layout. Our first upload failed on the archive shape while every one
    of its 2,370,727 prediction lines was correct, so checking only the text is
    demonstrably not enough.
    """
    path = mind_format.output_path(out_dir)

    ids: list[str] = []
    lengths: list[int] = []

    def stream() -> Iterator[str]:
        for line, impression_id, n in mind_lines(source):
            ids.append(impression_id)
            lengths.append(n)
            yield line

    written = fmt.write_lines(stream(), path)
    summary = fmt.validate_file(path, ids, lengths)
    summary["path"] = str(path)
    summary["bytes"] = path.stat().st_size
    if written != summary["lines"]:
        raise fmt.PredictionFormatError(f"wrote {written} lines but read back {summary['lines']}")

    archive = fmt.zip_prediction(
        path,
        mind_format.archive_path(out_dir),
        member_dir=mind_format.MEMBER_DIR,
    )
    summary["archive"] = fmt.validate_archive(archive, mind_format.MEMBER, summary["lines"])
    return summary


