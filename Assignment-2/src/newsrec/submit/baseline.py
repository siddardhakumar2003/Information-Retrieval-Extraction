def ebnerd_baseline_ranks(candidates: pl.Series) -> pl.Series:
    """Ranks 1..n per row, by `article_id` ascending, as a list column.

    Vectorised in polars rather than looped in Python: 13,536,710 rows holding
    205,925,868 candidate ids is where a per-row `argsort` stops being free.

    `rank("ordinal")` gives, for each element, its position in ascending order
    -- which IS the inverse permutation the submission wants, directly. No
    separate inversion step, and therefore no chance of writing the permutation
    by mistake, which is the failure `format.ranks_from_scores` exists to
    prevent on the per-row path.

    Ordinal, not "min" or "dense": tied ids would otherwise share a rank, and
    `1/rank` needs them distinct. Ids within one impression are distinct anyway,
    so this is belt and braces rather than a real tie-break.
    """
    return candidates.list.eval(pl.element().rank("ordinal").cast(pl.Int64))


def _ebnerd_lines(chunk: pl.DataFrame) -> list[str]:
    """`<impression_id> [r1,r2,...]` for every row of `chunk`, in order."""
    ranked = chunk.with_columns(
        ebnerd_baseline_ranks(pl.col("article_ids_inview")).alias("ranks")
    ).with_columns(
        (
            pl.col("impression_id").cast(pl.Utf8)
            + pl.lit(" [")
            + pl.col("ranks").cast(pl.List(pl.Utf8)).list.join(",")
            + pl.lit("]")
        ).alias("line")
    )
    return ranked["line"].to_list()


def write_ebnerd_baseline(
    out_dir: Path,
    source: Path | None = None,
    chunk: int = ebnerd_test.DEFAULT_CHUNK,
) -> dict:
    """Write, archive and validate an EB-NeRD baseline submission.

    The expectations handed to the validator are generators, so the 13.5M ids
    and lengths are never all in memory at once -- and they are re-read from the
    parquet rather than remembered from the write, so the validation is a
    genuine second pass over the source rather than a check against the same
    in-memory list that produced the file.
    """
    shape = ebnerd_test.check_shape(source)
    path = ebnerd_format.output_path(out_dir)

    def lines() -> Iterator[str]:
        for frame in ebnerd_test.iter_chunks(source, chunk):
            yield from _ebnerd_lines(frame)

    written = fmt.write_lines(lines(), path)

    def expected_ids() -> Iterator[str]:
        for frame in ebnerd_test.iter_chunks(source, chunk, columns=("impression_id",)):
            yield from (str(v) for v in frame["impression_id"].to_list())

    def expected_lengths() -> Iterator[int]:
        for frame in ebnerd_test.iter_chunks(source, chunk, columns=("article_ids_inview",)):
            yield from frame["article_ids_inview"].list.len().to_list()

    summary = fmt.validate_file(path, expected_ids(), expected_lengths())
    summary["path"] = str(path)
    summary["bytes"] = path.stat().st_size
    summary["source_shape"] = shape
    if written != summary["lines"]:
        raise fmt.PredictionFormatError(f"wrote {written} lines but read back {summary['lines']}")

    archive = fmt.zip_prediction(
        path, ebnerd_format.archive_path(out_dir), member_dir=ebnerd_format.MEMBER_DIR
    )
    summary["archive"] = fmt.validate_archive(archive, ebnerd_format.MEMBER, summary["lines"])
    return summary
